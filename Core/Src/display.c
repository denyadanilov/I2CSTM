static uint8_t framebuffer[DISPLAY_WIDTH * (DISPLAY_HEIGHT / 8U)];
static OLED_Config oled;
static uint8_t initialized;

static int32_t display_send_i2c(void *context, uint8_t address,
                                const uint8_t *data, size_t length) {
  if (length > UINT16_MAX) {
    return OLED_ERR_INVALID_ARG;
  }
  return HAL_I2C_Master_Transmit((I2C_HandleTypeDef *)context,
                                 (uint16_t)(address << 1),
                                 (uint8_t *)data, (uint16_t)length,
                                 DISPLAY_I2C_TIMEOUT_MS) == HAL_OK
             ? OLED_OK
             : OLED_ERR_IO;
}

display_status_t display_init(I2C_HandleTypeDef *i2c) {
  if (i2c == NULL) {
    return DISPLAY_ERROR_ARGUMENT;
  }

  initialized = 0U;
  oled = (OLED_Config){
      .bus_type = OLED_BUS_I2C,
      .width = DISPLAY_WIDTH,
      .height = DISPLAY_HEIGHT,
      .user_context = i2c,
      .transport.i2c = {.i2c_address_7bit = DISPLAY_ADDRESS,
                        .send_fn = display_send_i2c}};
  if (OLED_Init(&oled) != OLED_OK) {
    return DISPLAY_ERROR_IO;
  }
  memset(framebuffer, 0, sizeof(framebuffer));
  initialized = 1U;
  return DISPLAY_OK;
}

display_status_t display_clear(void) {
  if (!initialized) {
    return DISPLAY_ERROR_NOT_INITIALIZED;
  }
  memset(framebuffer, 0, sizeof(framebuffer));
  return DISPLAY_OK;
}

display_status_t display_draw_text(uint16_t x, uint16_t y, const char *text) {
  const unsigned char *p;
  size_t count = 0U;

  if (!initialized) {
    return DISPLAY_ERROR_NOT_INITIALIZED;
  }
  if (text == NULL || x >= DISPLAY_WIDTH || y > DISPLAY_HEIGHT - 8U) {
    return DISPLAY_ERROR_ARGUMENT;
  }

  for (p = (const unsigned char *)text; *p != '\0'; ++p) {
    if (*p < 32U || *p > 126U || ++count > (DISPLAY_WIDTH - x) / FONT_ADVANCE) {
      return DISPLAY_ERROR_ARGUMENT;
    }
  }

  for (p = (const unsigned char *)text; *p != '\0'; ++p) {
    for (uint16_t col = 0U; col < FONT_ADVANCE; ++col) {
      uint8_t bits = col < FONT_WIDTH ? font[*p - 32U][col] : 0U;
      for (uint16_t row = 0U; row < 8U; ++row) {
        uint16_t pixel_y = y + row;
        size_t index = (size_t)(pixel_y / 8U) * DISPLAY_WIDTH + x + col;
        uint8_t mask = (uint8_t)(1U << (pixel_y % 8U));
        if (bits & (1U << row)) {
          framebuffer[index] |= mask;
        } else {
          framebuffer[index] &= (uint8_t)~mask;
        }
      }
    }
    x += FONT_ADVANCE;
  }
  return DISPLAY_OK;
}

display_status_t display_flush(void) {
  if (!initialized) {
    return DISPLAY_ERROR_NOT_INITIALIZED;
  }
  return OLED_DrawBitmap(&oled, framebuffer, sizeof(framebuffer)) == OLED_OK
             ? DISPLAY_OK
             : DISPLAY_ERROR_IO;
}
